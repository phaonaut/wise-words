// Lists every clip the app can play and writes:
//   scripts/voice/manifest.json  (each clip's key, file name and the text to record)
//   src/data/clips.ts            (the app's lookup from text to audio file)
// Run with: npm run voice:list   (then npm run voice:prompts to update the Gemini scripts)
import { writeFileSync } from 'node:fs';

import { BUILT_IN_LISTS, SENTENCES } from '../../src/data/dolch.ts';
import { PRAISE, TRY_AGAIN } from '../../src/data/fun.ts';

// Phrases the app says around words. Keep in sync with the say(...) calls in the app.
const PHRASES = [
  'Find the word',
  'Find',
  'That says',
  'This word is',
  'Spell',
  'is spelled',
  'apostrophe',
  'Great job!',
  'You got a new sticker!',
  'Hi! Ready to learn?',
  'Flashcards',
  'Hear and Find',
  'Spell It',
  'I can read!',
  ...PRAISE,
  ...TRY_AGAIN,
];

// Phrases recorded with different text so they sound right. Titles get "!" so they don't trail off.
const SAY = {
  Flashcards: 'Flashcards!',
  'Hear and Find': 'Hear and Find!',
  'Spell It': 'Spell it!',
};

const slug = (text) =>
  text
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const clips = new Map();
const add = (key, file, text) => {
  if (!clips.has(key)) clips.set(key, { key, file, text });
};

for (const list of BUILT_IN_LISTS) {
  for (const { word } of list.words) add(`w:${word.toLowerCase()}`, `w-${slug(word)}`, `${word}.`);
}
for (const sentence of Object.values(SENTENCES)) add(`p:${sentence}`, `s-${slug(sentence)}`, sentence);
for (const phrase of PHRASES) add(`p:${phrase}`, `p-${slug(phrase)}`, SAY[phrase] ?? phrase);
for (const ch of 'abcdefghijklmnopqrstuvwxyz') add(`l:${ch}`, `l-${ch}`, `${ch.toUpperCase()}.`);

const all = [...clips.values()];
writeFileSync(new URL('./manifest.json', import.meta.url), JSON.stringify(all, null, 1));

writeFileSync(
  new URL('../../src/data/clips.ts', import.meta.url),
  `// Generated by scripts/voice/manifest.mjs. Do not edit by hand.\n` +
    `// Keys: "w:<word>" for words, "l:<letter>" for letter names, "p:<text>" for phrases and sentences.\n` +
    `export const CLIPS: Record<string, number> = {\n` +
    all.map((c) => `  ${JSON.stringify(c.key)}: require('../../assets/audio/${c.file}.mp3'),`).join('\n') +
    `\n};\n`,
);

console.log(`${all.length} clips listed`);
