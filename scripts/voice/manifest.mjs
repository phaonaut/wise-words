// Lists every clip the app can play and writes:
//   scripts/voice/manifest.json  (what generate.py should record)
//   src/data/clips.ts            (the app's lookup from text to audio file)
// Run with: npm run voice   (this script, then generate.py)
import { writeFileSync } from 'node:fs';

import { BUILT_IN_LISTS, SENTENCES } from '../../src/data/dolch.ts';
import { PRAISE, TRY_AGAIN } from '../../src/data/fun.ts';

// Phrases the app says around words. Keep in sync with the say(...) calls in the app.
const PHRASES = [
  'Find the word',
  'Find',
  'That says',
  'This word is',
  'Spell',
  'is spelled',
  'apostrophe',
  'Great job!',
  'You got a new sticker!',
  'Hi! Ready to learn?',
  'Flashcards',
  'Hear and Find',
  'Spell It',
  'I can read!',
  ...PRAISE,
  ...TRY_AGAIN,
];

const LETTER_NAMES = {
  a: 'ay', b: 'bee', c: 'see', d: 'dee', e: 'ee', f: 'eff', g: 'jee', h: 'aitch', i: 'eye',
  j: 'jay', k: 'kay', l: 'ell', m: 'em', n: 'en', o: 'oh', p: 'pee', q: 'cue', r: 'are',
  s: 'ess', t: 'tee', u: 'you', v: 'vee', w: 'double you', x: 'ex', y: 'why', z: 'zee',
};

// How the voice should say words it could get wrong on their own (Kokoro/misaki phonemes).
const PRONOUNCE = {
  a: '[a](/ə/)',
  live: '[live](/lˈɪv/)',
  read: '[read](/ɹˈid/)',
};

const slug = (text) =>
  text
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

// Single words and letter names are said slower, like a teacher reading a flashcard.
const SLOW = 0.75;

const clips = new Map();
const add = (key, file, text, speed) => {
  if (!clips.has(key)) clips.set(key, speed ? { key, file, text, speed } : { key, file, text });
};

for (const list of BUILT_IN_LISTS) {
  for (const { word } of list.words) {
    const k = word.toLowerCase();
    add(`w:${k}`, `w-${slug(word)}`, `${PRONOUNCE[k] ?? word}.`, SLOW);
  }
}
for (const sentence of Object.values(SENTENCES)) add(`p:${sentence}`, `s-${slug(sentence)}`, sentence);
for (const phrase of PHRASES) add(`p:${phrase}`, `p-${slug(phrase)}`, phrase);
for (const [ch, name] of Object.entries(LETTER_NAMES)) add(`l:${ch}`, `l-${ch}`, `${name}.`, SLOW);

const all = [...clips.values()];
writeFileSync(new URL('./manifest.json', import.meta.url), JSON.stringify(all, null, 1));

// The app's voice choices. Each has its own folder in assets/audio (see VOICE_SETS in generate.py).
const VOICES = ['female', 'male'];

const table = (voice) =>
  `  ${voice}: {\n` +
  all.map((c) => `    ${JSON.stringify(c.key)}: require('../../assets/audio/${voice}/${c.file}.mp3'),`).join('\n') +
  `\n  },`;

writeFileSync(
  new URL('../../src/data/clips.ts', import.meta.url),
  `// Generated by scripts/voice/manifest.mjs. Do not edit by hand.\n` +
    `// Keys: "w:<word>" for words, "l:<letter>" for letter names, "p:<text>" for phrases and sentences.\n` +
    `export type VoiceName = ${VOICES.map((v) => `'${v}'`).join(' | ')};\n\n` +
    `export const CLIPS: Record<VoiceName, Record<string, number>> = {\n${VOICES.map(table).join('\n')}\n};\n`,
);

console.log(`${all.length} clips listed`);
