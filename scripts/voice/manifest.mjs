// Lists every clip the app can play and writes:
//   scripts/voice/manifest.json  (each clip's key, file name and the text to record)
//   src/data/clips.ts            (the app's lookup from text to audio file, for clips that exist)
// Run with: npm run voice:list   (then npm run voice:prompts to update the Gemini scripts)
import { existsSync, writeFileSync } from 'node:fs';

import { BUILT_IN_LISTS, SENTENCES } from '../../src/data/dolch.ts';
import { PRAISE, TRY_AGAIN } from '../../src/data/fun.ts';

// Phrases the app says around words. Keep in sync with the say(...) calls in the app.
const PHRASES = [
  'Find the word',
  'Find',
  'That says',
  'This word is',
  'Spell',
  'is spelled',
  'apostrophe',
  'Great job!',
  'You got a new sticker!',
  'Hi! Ready to learn?',
  'Flashcards',
  'Hear and Find',
  'Spell It',
  'I can read!',
  ...PRAISE,
  ...TRY_AGAIN,
];

// Math: game titles, questions, and the joining words said between numbers ("3" "plus" "2" "is" "5").
// Keep in sync with the say(...) calls in the math screens and the prompts in src/lib/math.ts.
const MATH_PHRASES = [
  'Math',
  'Count It',
  'Add and Subtract',
  'More or Less',
  'How many?',
  'What is',
  'plus',
  'take away',
  'minus',
  'is',
  'Which has more?',
  'Which has fewer?',
  'Which number is bigger?',
  'Which number is smaller?',
  'Which number is the biggest?',
  'Which number is the smallest?',
];

// Phrases recorded with different text so they sound right. Titles get "!" so they don't trail off.
const SAY = {
  Flashcards: 'Flashcards!',
  'Hear and Find': 'Hear and Find!',
  'Spell It': 'Spell it!',
  Math: 'Math!',
  'Count It': 'Count it!',
  'Add and Subtract': 'Add and subtract!',
  'More or Less': 'More or less!',
};

// Numbers are written out so the voice can't misread them ("zero", not "oh").
const ONES = [
  'zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven',
  'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen',
];
const TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
const numberWords = (n) =>
  n === 100 ? 'one hundred' : n < 20 ? ONES[n] : TENS[Math.floor(n / 10)] + (n % 10 ? `-${ONES[n % 10]}` : '');
// The math games say numbers up to this.
const MAX_NUMBER = 100;

const slug = (text) =>
  text
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const clips = new Map();
// `batch` puts a clip in its own Gemini recording batch (see gemini-prompts.mjs).
const add = (key, file, text, batch) => {
  if (!clips.has(key)) clips.set(key, batch ? { key, file, text, batch } : { key, file, text });
};

for (const list of BUILT_IN_LISTS) {
  for (const { word } of list.words) add(`w:${word.toLowerCase()}`, `w-${slug(word)}`, `${word}.`);
}
for (const sentence of Object.values(SENTENCES)) add(`p:${sentence}`, `s-${slug(sentence)}`, sentence);
for (const phrase of PHRASES) add(`p:${phrase}`, `p-${slug(phrase)}`, SAY[phrase] ?? phrase);
for (const ch of 'abcdefghijklmnopqrstuvwxyz') add(`l:${ch}`, `l-${ch}`, `${ch.toUpperCase()}.`);
for (const phrase of MATH_PHRASES) add(`p:${phrase}`, `p-${slug(phrase)}`, SAY[phrase] ?? phrase, 'math-phrases');
for (let n = 0; n <= MAX_NUMBER; n++) {
  add(`n:${n}`, `n-${n}`, `${numberWords(n)}.`, n <= 50 ? 'numbers-1' : 'numbers-2');
}

const all = [...clips.values()];
writeFileSync(new URL('./manifest.json', import.meta.url), JSON.stringify(all, null, 1));

// Only clips that have been recorded go in the app's table. The app reads anything else with the device voice.
const recorded = all.filter((c) => existsSync(new URL(`../../assets/audio/${c.file}.mp3`, import.meta.url)));

writeFileSync(
  new URL('../../src/data/clips.ts', import.meta.url),
  `// Generated by scripts/voice/manifest.mjs. Do not edit by hand.\n` +
    `// Keys: "w:<word>" for words, "l:<letter>" for letter names, "n:<number>" for numbers,\n` +
    `// and "p:<text>" for phrases and sentences.\n` +
    `export const CLIPS: Record<string, number> = {\n` +
    recorded.map((c) => `  ${JSON.stringify(c.key)}: require('../../assets/audio/${c.file}.mp3'),`).join('\n') +
    `\n};\n`,
);

console.log(`${all.length} clips listed, ${all.length - recorded.length} not recorded yet`);
