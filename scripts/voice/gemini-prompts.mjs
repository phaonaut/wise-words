// Writes the scripts to paste into Google AI Studio's "Generate speech" (Gemini TTS), in batches:
//   scripts/voice/gemini-prompts.md    (what to paste, one batch at a time)
//   scripts/voice/gemini-batches.json  (which clip file each line becomes, used by split.py)
// Run after manifest.mjs: node scripts/voice/gemini-prompts.mjs
import { readFileSync, writeFileSync } from 'node:fs';

import { BUILT_IN_LISTS } from '../../src/data/dolch.ts';

const manifest = JSON.parse(readFileSync(new URL('./manifest.json', import.meta.url), 'utf8'));
const byKey = new Map(manifest.map((c) => [c.key, c]));

const STYLE = {
  words:
    'A warm, patient kindergarten teacher reading sight word flashcards to a five-year-old. Say each word once, slowly and clearly, in standard American English. Leave a long pause after every word. Do not say anything else.',
  letters:
    'A warm, patient kindergarten teacher saying the names of the letters of the alphabet to a five-year-old. Say each letter name once, slowly and clearly. Leave a long pause after every letter. Do not say anything else.',
  lines:
    'A warm, cheerful kindergarten teacher talking to a five-year-old. Say each line once, clearly, at a relaxed pace, in standard American English. Leave a long pause after every line. Do not say anything else.',
};

const batches = [];
const used = new Set();

// Words, one batch per list.
const LIST_IDS = { 'dolch-prek': 'words-prek', 'dolch-k': 'words-k', 'dolch-1': 'words-1', 'dolch-2': 'words-2', 'dolch-3': 'words-3' };
for (const list of BUILT_IN_LISTS) {
  const items = [];
  for (const { word } of list.words) {
    const k = word.toLowerCase();
    if (used.has(k)) continue;
    used.add(k);
    items.push({ file: byKey.get(`w:${k}`).file, text: `${word}.` });
  }
  batches.push({ id: LIST_IDS[list.id] ?? list.id, title: list.name, style: STYLE.words, items });
}

const of = (prefix) => manifest.filter((c) => c.key.startsWith(prefix));

batches.push({
  id: 'letters',
  title: 'Letter names',
  style: STYLE.letters,
  items: of('l:').map((c) => ({ file: c.file, text: c.text })),
});

batches.push({
  id: 'phrases',
  title: 'Phrases',
  style: STYLE.lines,
  items: of('p:')
    .filter((c) => c.file.startsWith('p-'))
    .map((c) => ({ file: c.file, text: c.text })),
});

const sentences = of('p:').filter((c) => c.file.startsWith('s-'));
const half = Math.ceil(sentences.length / 2);
[sentences.slice(0, half), sentences.slice(half)].forEach((part, i) =>
  batches.push({
    id: `sentences-${i + 1}`,
    title: `Sentences, part ${i + 1}`,
    style: STYLE.lines,
    items: part.map((c) => ({ file: c.file, text: c.text })),
  }),
);

writeFileSync(new URL('./gemini-batches.json', import.meta.url), JSON.stringify(batches, null, 1));

const md = [
  '# Wise Words: Gemini voice prompts',
  '',
  'Generated by `scripts/voice/gemini-prompts.mjs`.',
  '',
  '1. Open aistudio.google.com → **Generate speech**, single speaker, model **gemini-3.8-flash-tts**.',
  '2. Pick one voice and use it for every batch (the app uses one voice throughout).',
  '3. For each batch, paste the **style** into the style instructions box and the **text** into the text box.',
  '4. Generate, listen, and download the WAV. Rename it to the batch name (for example `words-prek.wav`).',
  '5. Put the files in `voice-recordings/` in the project folder, then run `scripts/voice/split.py` (see the README).',
  '',
  ...batches.flatMap((b) => [
    `## ${b.id}.wav: ${b.title} (${b.items.length})`,
    '',
    'Style:',
    '',
    '```',
    b.style,
    '```',
    '',
    'Text:',
    '',
    '```',
    ...b.items.map((it) => `${it.text} <long pause>`),
    '```',
    '',
  ]),
].join('\n');
writeFileSync(new URL('./gemini-prompts.md', import.meta.url), md);

